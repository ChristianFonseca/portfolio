import { chromium } from "playwright"
import { execFileSync } from "node:child_process"
const psql = (q) => execFileSync("docker", ["exec", "-i", "pg-guardrails-test", "psql", "-U", "postgres", "-tA", "-c", q]).toString().trim()
const B = "http://admin.localhost:3300"
const b = await chromium.launch()
const pg = await b.newPage({ viewport: { width: 1360, height: 900 } })
await pg.goto(`${B}/login`, { waitUntil: "networkidle" })
await pg.locator('input[type="email"]').fill("test@example.com")
await pg.locator('input[type="password"]').fill("test-guardrails-123")
await pg.locator('button[type="submit"]').click()
await pg.waitForURL((u) => !u.pathname.startsWith("/login"))
await pg.goto(`${B}/config`, { waitUntil: "networkidle" })
await pg.locator("#chat-global").fill("0")
console.log("aviso en vivo con 0:", await pg.getByText("El chat está apagado").count() > 0)
await pg.locator("#chat-global").fill("50")
await pg.locator("#chat-ips").fill("203.0.113.7")
await pg.getByRole("button", { name: "Guardar chat" }).click()
await pg.getByText("Configuración del chat guardada").waitFor({ timeout: 10000 })
console.log("setting guardado:", psql("select value from settings where key='chat_global_daily_limit'"))
const detail = psql("select detail from admin_audit where action='settings.chat' order by id desc limit 1")
console.log("bitácora:", detail)
const d = JSON.parse(detail)
console.log("antes/después del tope:", d.globalLimit?.before, "→", d.globalLimit?.after, "| allowlist:", JSON.stringify(d.allowlist))
console.log("campos sin cambios omitidos:", !("extraContext" in d) || d.extraContext === undefined)
await b.close()
